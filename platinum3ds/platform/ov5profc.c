/* run 101 field_prof (Debug tab "Load-hitch profiler", default 0; config field_prof=1): per-function game-thread timing for every cross-object
   call made by overlay005 (field map) code plus overlay/NARC/LZ/FS loaders (ov5prof.S, generated by genprof.py).
   Each wrapped call on the game thread pushes {fn, return address, start tick, child time} on a shadow stack; the
   return goes through P3DS_ProfRet. Self time = inclusive - wrapped children. P3DS_ProfFrame() (each present) logs the
   top functions of any frame over 50 ms, then clears. */
#include <3ds.h>
#include <string.h>
extern void PSPNativeMemLog(const char *, ...);
extern const char *P3DS_ProfNames[]; extern int P3DS_ProfCount; extern void P3DS_ProfRet(void);
#define NF 1500
int P3DS_ProfOn; static u32 gameTls; static int depth;
static struct { int f; u32 lr; u64 t0, child; } st[256];
static u64 selfT[NF], inclT[NF]; static u32 calls[NF];
static inline u32 tls(void) { u32 v; __asm__ volatile("mrc p15,0,%0,c13,c0,3" : "=r"(v)); return v; }
static unsigned nEnter, nTaken;
u32 P3DS_ProfEnter(int f, u32 lr) {
    nEnter++;
    if (!gameTls || tls() != gameTls || depth >= 256 || f < 0 || f >= NF) return lr;
    st[depth].f = f; st[depth].lr = lr; st[depth].child = 0; st[depth].t0 = svcGetSystemTick(); depth++; nTaken++;
    return (u32)P3DS_ProfRet;
}
u32 P3DS_ProfExit(void) {
    u64 now = svcGetSystemTick(); depth--; const int f = st[depth].f; u64 dt = now - st[depth].t0;
    selfT[f] += dt - st[depth].child; inclT[f] += dt; calls[f]++;
    if (depth > 0) st[depth - 1].child += dt;
    return st[depth].lr;
}
void P3DS_ProfFrame(unsigned frameMs) {
    if (!gameTls) gameTls = tls();
    if (!P3DS_ProfOn) return;
    if (depth) return; /* mid-call (present inside a wrapped call): keep counting */
    if (frameMs >= 70) {
        PSPNativeMemLog("[PROF] frame %u ms (depth %d, wrapped calls %u, timed %u, flag %d @%p tls %08x/%08x) top self / incl:", frameMs, depth, nEnter, nTaken, *(volatile int *)&P3DS_ProfOn, (void *)&P3DS_ProfOn, (unsigned)gameTls, (unsigned)tls());
        for (int k = 0; k < 14; k++) { int b = -1; for (int i = 0; i < P3DS_ProfCount && i < NF; i++) if (selfT[i] && (b < 0 || selfT[i] > selfT[b])) b = i;
            if (b < 0) break;
            PSPNativeMemLog("[PROF]   %-40s self %6u us incl %6u us x%u", P3DS_ProfNames[b], (unsigned)(selfT[b] / 268), (unsigned)(inclT[b] / 268), calls[b]); selfT[b] = 0; }
        for (int k = 0; k < 8; k++) { int b = -1; for (int i = 0; i < P3DS_ProfCount && i < NF; i++) if (inclT[i] && (b < 0 || inclT[i] > inclT[b])) b = i;
            if (b < 0) break; PSPNativeMemLog("[PROF]   incl %-40s %6u us x%u", P3DS_ProfNames[b], (unsigned)(inclT[b] / 268), calls[b]); inclT[b] = 0; }
    }
    nEnter = nTaken = 0;
    memset(selfT, 0, sizeof selfT); memset(inclT, 0, sizeof inclT); memset(calls, 0, sizeof calls);
}
