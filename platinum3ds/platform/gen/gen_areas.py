#!/usr/bin/env python3
"""run 64: map header -> follower talk area table (from the decomp's map header NAMES only, nothing from the ROM).
usage: gen_areas.py <generated/map_headers.h> > ../p3ds_areas.h"""
import re, sys
names = {}
for m in re.finditer(r'MAP_HEADER_(\w+)\s*=\s*(\d+)', open(sys.argv[1]).read()):
    if int(m.group(2)) < 1000 and m.group(1) not in ('COUNT', 'INVALID', 'DYNAMIC'): names[int(m.group(2))] = m.group(1)
TOWNS = ['TWINLEAF_TOWN','SANDGEM_TOWN','JUBILIFE_CITY','OREBURGH_CITY','FLOAROMA_TOWN','ETERNA_CITY','HEARTHOME_CITY',
         'SOLACEON_TOWN','VEILSTONE_CITY','PASTORIA_CITY','CELESTIC_TOWN','CANALAVE_CITY','SNOWPOINT_CITY','SUNYSHORE_CITY',
         'FIGHT_AREA','SURVIVAL_AREA','RESORT_AREA']
# categories (keep in sync with p3ds_foltalk.c)
OTHER, TOWN, ROUTE, SEA, LAKE, LEGEND, FOREST, CENTER, MART, GYM, MARSH, SPOOKY, LEAGUE, GALACTIC, INDOOR, SNOW, CAVE = range(17)
LEGENDS = ['SPEAR_PILLAR','HALL_OF_ORIGIN','TURNBACK','SENDOFF_SPRING','DISTORTION','STARK_MOUNTAIN','NEWMOON','FULLMOON',
           'FLOWER_PARADISE','SNOWPOINT_TEMPLE','ICEBERG_RUINS','ROCK_PEAK_RUINS','IRON_RUINS','VERITY_CAVERN','VALOR_CAVERN','ACUITY_CAVERN']
def cat(n):
    if any(k in n for k in LEGENDS): return LEGEND, 0
    if n.startswith('LAKE_') or 'LAKEFRONT' in n: return LAKE, 0
    if 'POKECENTER' in n: return CENTER, 0
    if n.endswith('_MART') or 'MARKET' in n or 'DEPARTMENT_STORE' in n or 'VEILSTONE_STORE' in n: return MART, 0
    if '_GYM' in n: return GYM, 0
    if 'POKEMON_LEAGUE' in n or 'VICTORY_ROAD' in n: return LEAGUE, 0
    if 'OLD_CHATEAU' in n or 'LOST_TOWER' in n: return SPOOKY, 0
    if 'GREAT_MARSH' in n: return MARSH, 0
    if 'FOREST' in n: return FOREST, 0
    if 'GALACTIC' in n: return GALACTIC, 0
    m = re.match(r'ROUTE_(\d+)(_(NORTH|SOUTH|EAST|WEST))?$', n)
    if m:
        r = int(m.group(1))
        if r in (216, 217): return SNOW, r - 200
        if r in (219, 220, 221, 223, 226, 230): return SEA, r - 200
        return ROUTE, r - 200
    for i, t in enumerate(TOWNS):
        if n == t: return (SNOW if t == 'SNOWPOINT_CITY' else TOWN), i + 1
        if n.startswith(t + '_'): return INDOOR, i + 1
    return OTHER, 0
mx = max(names)
print('/* generated by gen/gen_areas.py from the decomp map header names (no ROM data). area = cat | sub << 5 */')
print('static const unsigned short kP3dsArea[%d] = {' % (mx + 1))
row = []
for i in range(mx + 1):
    c, s = cat(names.get(i, ''))
    row.append(str(c | s << 5))
for i in range(0, len(row), 24): print('  ' + ','.join(row[i:i + 24]) + ',')
print('};')
