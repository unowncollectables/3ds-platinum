#!/usr/bin/env python3
"""run 64: map header id -> readable place name for the settings app Map tab, from the decomp's map header
IDENTIFIERS only (e.g. MAP_HEADER_ROUTE_210_SOUTH -> "Route 210 South"); nothing from the ROM.
usage: gen_areanames.py <generated/map_headers.h> > ../p3ds_areanames.h"""
import re, sys
names = {}
for m in re.finditer(r'MAP_HEADER_(\w+)\s*=\s*(\d+)', open(sys.argv[1]).read()):
    if int(m.group(2)) < 1000 and m.group(1) not in ('COUNT', 'INVALID', 'DYNAMIC'): names[int(m.group(2))] = m.group(1)
KEEP = {'B1F', 'B2F', 'B3F', 'B4F', 'B5F', 'B6F', '1F', '2F', '3F', '4F', '5F', '6F', '7F', 'TV', 'PC', 'HQ', 'UG', 'II', 'III'}
def pretty(n):
    w = []
    for p in n.split('_'):
        if p in KEEP or re.match(r'^\d+F$|^B\d+F$|^R\d+$', p): w.append(p)
        elif p == 'POKECENTER': w.append('Pok\\xe9" "mon Center')
        elif p == 'POKEMON': w.append('Pok\\xe9" "mon')
        else: w.append(p.capitalize())
    return ' '.join(w)
mx = max(names)
print('/* generated by gen/gen_areanames.py from the decomp map header identifiers (no ROM data) */')
print('static const char *const kP3dsAreaName[%d] = {' % (mx + 1))
for i in range(mx + 1): print('  "%s",' % pretty(names.get(i, '')))
print('};')
